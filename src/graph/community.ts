// ---------------------------------------------------------------------------
// Community Detection — Label Propagation (4.5 part 2)
// ---------------------------------------------------------------------------
//
// Implements a Leiden-inspired label propagation algorithm for community
// detection in the unified DiagnosticGraph.  The algorithm is pure TypeScript
// with no external dependencies and runs in O(iterations × edges) time,
// which is well within budget for K8s-scale graphs (<10K nodes).
//
// After detecting communities, summaries are generated and stored as
// retrievable IndexedChunks so that the LLM receives "big picture" context
// (e.g. "database stack: db StatefulSet, db Service, 2 Secrets, 1 PVC in
// namespace database") without needing to read every individual artifact.
//
// The function `buildCommunityNodes` wires the results into the diagnostic
// graph as the top hierarchy layer (application components from 4.7), sitting
// above WorkloadGroup nodes (middle layer) and individual resource nodes
// (bottom layer).

import type { DiagnosticGraph, DiagnosticGraphNode } from './diagnostic-graph.js';
import type { IndexedChunk } from '../ai/chunk-indexer.js';

// ---------------------------------------------------------------------------
// Community
// ---------------------------------------------------------------------------

/**
 * A single community of related graph nodes, as produced by
 * {@link detectCommunities}.
 *
 * Fields:
 * - `id`      — stable identifier (`community-{index}`)
 * - `label`   — human-readable name derived from dominant namespace / kind
 * - `nodeIds` — IDs of all nodes belonging to this community
 * - `summary` — generated by {@link generateCommunitySummary}; empty string
 *               until summary generation is called
 */
export interface Community {
  id: string;
  label: string;
  nodeIds: string[];
  summary: string;
}

// ---------------------------------------------------------------------------
// Internal adjacency helpers
// ---------------------------------------------------------------------------

/**
 * Builds an undirected adjacency list from the graph's edges.
 * Both `source → target` and `target → source` directions are included so
 * that label propagation explores all structural connections regardless of
 * edge direction.
 */
function buildAdjacency(graph: DiagnosticGraph): Map<string, Set<string>> {
  const adj = new Map<string, Set<string>>();

  for (const nodeId of graph.nodes.keys()) {
    adj.set(nodeId, new Set());
  }

  for (const edge of graph.edges) {
    // Skip self-loops
    if (edge.source === edge.target) continue;

    const src = adj.get(edge.source);
    const tgt = adj.get(edge.target);

    // Only add edges where both endpoints are known nodes
    if (src !== undefined && tgt !== undefined) {
      src.add(edge.target);
      tgt.add(edge.source);
    }
  }

  return adj;
}

// ---------------------------------------------------------------------------
// detectCommunities — label propagation
// ---------------------------------------------------------------------------

/** Maximum number of label propagation iterations before forcing convergence. */
const MAX_ITERATIONS = 50;

/**
 * Detects communities in the {@link DiagnosticGraph} using label propagation.
 *
 * **Algorithm (Leiden-inspired, simplified for K8s-scale graphs):**
 * 1. Initialise: each node receives its own node ID as its label.
 * 2. Update pass: for every node (processed in deterministic sorted order for
 *    reproducibility), adopt the most frequent label among its undirected
 *    neighbours.  Ties are broken by lexicographic order of the label string
 *    (smaller = wins) to ensure deterministic convergence.
 * 3. Repeat until no label changes or `MAX_ITERATIONS` is reached.
 * 4. Group nodes by their final label; each group is one community.
 *
 * **Properties:**
 * - Pure TypeScript, no external dependencies.
 * - Deterministic (sorted iteration order + lexicographic tie-breaking).
 * - Correctly handles isolated nodes (each becomes its own community).
 * - Correctly handles disconnected components (each component is one or more
 *   communities depending on internal density).
 * - O(iterations × edges) — well within budget for <10K node graphs.
 *
 * @param graph The {@link DiagnosticGraph} to analyse.
 * @returns Array of {@link Community} objects.  Empty for an empty graph.
 */
export function detectCommunities(graph: DiagnosticGraph): Community[] {
  const nodeIds = [...graph.nodes.keys()];
  if (nodeIds.length === 0) return [];

  const adj = buildAdjacency(graph);

  // Step 1: Initialise each node with its own label
  const labels = new Map<string, string>();
  for (const id of nodeIds) {
    labels.set(id, id);
  }

  // Step 2: Iterative label propagation
  // Sorted order ensures deterministic behaviour across runs
  const sortedIds = [...nodeIds].sort();

  for (let iter = 0; iter < MAX_ITERATIONS; iter++) {
    let changed = false;

    for (const nodeId of sortedIds) {
      const neighbours = adj.get(nodeId);
      if (!neighbours || neighbours.size === 0) continue;

      // Count frequency of each neighbour's label
      const freq = new Map<string, number>();
      for (const neighbourId of neighbours) {
        const lbl = labels.get(neighbourId);
        if (lbl === undefined) continue;
        freq.set(lbl, (freq.get(lbl) ?? 0) + 1);
      }

      if (freq.size === 0) continue;

      // Find the most frequent label; break ties lexicographically
      let bestLabel = '';
      let bestCount = 0;
      for (const [lbl, count] of freq) {
        if (
          count > bestCount ||
          (count === bestCount && lbl < bestLabel)
        ) {
          bestCount = count;
          bestLabel = lbl;
        }
      }

      const currentLabel = labels.get(nodeId)!;
      if (bestLabel !== currentLabel) {
        labels.set(nodeId, bestLabel);
        changed = true;
      }
    }

    if (!changed) break;
  }

  // Step 3: Group nodes by final label
  const communityMap = new Map<string, string[]>();
  for (const [nodeId, label] of labels) {
    if (!communityMap.has(label)) {
      communityMap.set(label, []);
    }
    communityMap.get(label)!.push(nodeId);
  }

  // Step 4: Build Community objects (sort by representative label for stability)
  const sortedLabels = [...communityMap.keys()].sort();
  const communities: Community[] = sortedLabels.map((lbl, idx) => ({
    id: `community-${idx}`,
    label: '',        // populated by generateCommunitySummary or buildCommunityNodes
    nodeIds: communityMap.get(lbl)!,
    summary: '',      // populated by generateCommunitySummary or buildCommunityNodes
  }));

  return communities;
}

// ---------------------------------------------------------------------------
// generateCommunitySummary
// ---------------------------------------------------------------------------

/**
 * Determines the dominant namespace for a community.
 *
 * Returns the namespace that appears most frequently in the node metadata,
 * or `undefined` if no namespace information is present.
 */
function dominantNamespace(
  nodeIds: string[],
  nodes: Map<string, DiagnosticGraphNode>,
): string | undefined {
  const nsCount = new Map<string, number>();
  for (const id of nodeIds) {
    const node = nodes.get(id);
    if (!node) continue;
    const data = node.data as Record<string, unknown>;
    const ns = typeof data['namespace'] === 'string' ? data['namespace'] : undefined;
    if (ns) {
      nsCount.set(ns, (nsCount.get(ns) ?? 0) + 1);
    }
  }
  if (nsCount.size === 0) return undefined;
  // Return the namespace with the highest count
  let best: string | undefined;
  let bestCount = 0;
  for (const [ns, count] of nsCount) {
    if (count > bestCount) {
      bestCount = count;
      best = ns;
    }
  }
  return best;
}

/**
 * Counts K8s resource kinds present in the community.
 *
 * Returns a `Map<kind, count>` from kind strings to node counts.
 * Nodes whose `data` does not carry a `kind` field are grouped under `""`.
 */
function countKinds(
  nodeIds: string[],
  nodes: Map<string, DiagnosticGraphNode>,
): Map<string, number> {
  const kindCount = new Map<string, number>();
  for (const id of nodeIds) {
    const node = nodes.get(id);
    if (!node) continue;
    const data = node.data as Record<string, unknown>;
    const kind = typeof data['kind'] === 'string' ? data['kind'] : node.nodeType;
    kindCount.set(kind, (kindCount.get(kind) ?? 0) + 1);
  }
  return kindCount;
}

/**
 * Generates a human-readable summary for a {@link Community}.
 *
 * The summary describes the community at a glance:
 * - Total node count
 * - Dominant namespace (if determinable)
 * - Resource kind breakdown
 *
 * Example output:
 * ```
 * Application component in namespace 'frontend' (5 nodes):
 *   Deployment ×1, Pod ×1, Service ×1, Secret ×1, ConfigMap ×1
 * ```
 *
 * @param community The community to summarise.
 * @param nodes     The full node map from {@link DiagnosticGraph.nodes}.
 * @returns Human-readable summary string.
 */
export function generateCommunitySummary(
  community: Community,
  nodes: Map<string, DiagnosticGraphNode>,
): string {
  const { nodeIds } = community;
  const totalNodes = nodeIds.length;

  const ns = dominantNamespace(nodeIds, nodes);
  const kindMap = countKinds(nodeIds, nodes);

  // Build the kind breakdown string, sorted alphabetically for stability
  const kindParts = [...kindMap.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .filter(([kind]) => kind !== '') // skip unnamed kinds
    .map(([kind, count]) => `${kind} ×${count}`);

  const nsLabel = ns ? `namespace '${ns}'` : 'multiple namespaces';
  const kindLabel =
    kindParts.length > 0
      ? `  ${kindParts.join(', ')}`
      : '  (no typed nodes)';

  return (
    `Application component in ${nsLabel} (${totalNodes} node${totalNodes !== 1 ? 's' : ''}):\n` +
    kindLabel
  );
}

