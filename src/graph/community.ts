// communityToChunk / communitiesToChunks
// ---------------------------------------------------------------------------

/**
 * Converts a {@link Community} to a retrievable {@link IndexedChunk}.
 *
 * The chunk uses the community summary as its content so that semantic and
 * lexical search can match high-level application component descriptions
 * (e.g. "database stack in namespace database, 5 nodes: StatefulSet, Pod,
 * Service, Secret, PVC") against diagnostic queries.
 *
 * The chunk's `identifiers` array contains the community's node IDs, which
 * enables lexical search to find the chunk by exact resource reference.
 *
 * @param community The community to convert.  Its `summary` field must be
 *   populated (call {@link generateCommunitySummary} before this function).
 * @returns An {@link IndexedChunk} ready for indexing and retrieval.
 */
export function communityToChunk(community: Community): IndexedChunk {
  const content = community.summary || `Community ${community.id} (${community.nodeIds.length} nodes)`;

  // Extract short names from node IDs for identifiers
  // Node IDs follow the pattern "Kind:namespace/name" or plain "id"
  const identifiers = community.nodeIds.map((nodeId) => {
    const slashIdx = nodeId.lastIndexOf('/');
    if (slashIdx >= 0) {
      return nodeId.slice(slashIdx + 1); // extract the name part
    }
    return nodeId;
  });

  // Add the community label if non-empty
  if (community.label) {
    identifiers.push(community.label);
  }

  return {
    id: `community:${community.id}`,
    artifactId: `community:${community.id}`,
    content,
    startLine: 1,
    endLine: 1,
    summary: content,
    identifiers,
    artifactCategory: 'analyzer',
    metadata: {
      communityId: community.id,
      communityLabel: community.label,
      memberCount: community.nodeIds.length,
    },
  };
}

/**
 * Converts an array of {@link Community} objects to retrievable
 * {@link IndexedChunk}s — one chunk per community.
 *
 * Summaries must be populated before calling this function (either via
 * {@link generateCommunitySummary} or {@link buildCommunityNodes}).
 *
 * @param communities Array of communities to convert.
 * @returns Array of {@link IndexedChunk}s ready for indexing.
 */
export function communitiesToChunks(communities: Community[]): IndexedChunk[] {
  return communities.map(communityToChunk);
}

// ---------------------------------------------------------------------------
// buildCommunityNodes — wire into the diagnostic graph (top hierarchy layer)
// ---------------------------------------------------------------------------

/** Node id format for application-component nodes: `app-component:{community-id}` */
function appComponentNodeId(communityId: string): string {
  return `app-component:${communityId}`;
}

/**
 * Derives a human-readable label for an application component from its
 * community members.
 *
 * Strategy:
 * 1. If all nodes share the same namespace, use the namespace as the label
 *    (e.g. `"frontend"`, `"database"`).
 * 2. Otherwise, use the dominant namespace with a `"+"` suffix indicating
 *    multi-namespace membership (e.g. `"monitoring+"`).
 * 3. If no namespace information is available, fall back to the community ID.
 */
function deriveComponentLabel(
  community: Community,
  nodes: Map<string, DiagnosticGraphNode>,
): string {
  const nsSet = new Set<string>();
  for (const id of community.nodeIds) {
    const node = nodes.get(id);
    if (!node) continue;
    const data = node.data as Record<string, unknown>;
    const ns = typeof data['namespace'] === 'string' ? data['namespace'] : undefined;
    if (ns) nsSet.add(ns);
  }

  if (nsSet.size === 0) return community.id;
  if (nsSet.size === 1) return [...nsSet][0]!;

  // Multi-namespace: dominant namespace + "+"
  const ns = dominantNamespace(community.nodeIds, nodes);
  return ns ? `${ns}+` : community.id;
}

/**
 * Detects communities in the graph, generates summaries, and adds
 * **application-component** nodes to the graph as the top hierarchy layer.
 *
 * This function:
 * 1. Runs {@link detectCommunities} on the current graph state.
 * 2. Generates a human-readable summary for each community via
 *    {@link generateCommunitySummary}.
 * 3. Derives a short label for each community (dominant namespace).
 * 4. Adds an `application-component` node per community to the graph.
 * 5. Adds `contains` edges from each component node to all member nodes.
 *
 * The returned communities have their `label` and `summary` fields populated.
 *
 * **Idempotency:** calling this function multiple times overwrites the
 * `application-component` nodes in-place (since {@link DiagnosticGraph.addNode}
 * is idempotent by ID), but may create duplicate `contains` edges.  For
 * production use, call this function exactly once after all structural and
 * causal edges are built.
 *
 * @param graph The {@link DiagnosticGraph} to mutate.  Should already have
 *   structural edges from {@link buildDiagnosticGraph} and, optionally,
 *   workload-group nodes from {@link buildWorkloadGroups}.
 * @returns The detected communities with `label` and `summary` populated.
 */
export function buildCommunityNodes(graph: DiagnosticGraph): Community[] {
  const communities = detectCommunities(graph);
  if (communities.length === 0) return [];

  for (const community of communities) {
    // Generate human-readable summary and label
    const summary = generateCommunitySummary(community, graph.nodes);
    const label = deriveComponentLabel(community, graph.nodes);

    community.summary = summary;
    community.label = label;

    const componentId = appComponentNodeId(community.id);

    // Add the application-component node
    graph.addNode({
      id: componentId,
      nodeType: 'application-component',
      data: {
        name: label,
        communityId: community.id,
        members: community.nodeIds,
        summary,
      },
      metadata: {
        communityId: community.id,
        label,
        memberCount: community.nodeIds.length,
      },
    });

    // Add "contains" edges to all member nodes
    let edgeIdx = 0;
    for (const memberId of community.nodeIds) {
      graph.addEdge({
        id: `contains:${community.id}:${edgeIdx++}`,
        source: componentId,
        target: memberId,
        type: 'contains',
        weight: 1.0,
      });
    }
  }

  return communities;
}
